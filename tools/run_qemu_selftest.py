"""Runs the deployed models on an emulated ESP32 and compares them with Python.

Step 1 writes test vectors from the test set and the final models. Step 2 builds
env:qemu_selftest. Step 3 boots it in Espressif's QEMU. Step 4 compares the emulated
chip's output with the same computation in Python, for vectors and for demo clips.

    python tools/run_qemu_selftest.py

Needs Espressif QEMU in .tools/qemu. QEMU proves correct behaviour of the compiled
Xtensa code. It is not cycle accurate, so timing must come from a real board.
"""
import json
import os
import re
import subprocess
import sys
import queue
import threading
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from ml.common import RESULTS, load_split, rf_features  # noqa: E402
from ml.core import CLASSES, GOOD_SQ, READY, rf_predict, rhythm, rhythm_rule, run_core  # noqa: E402
from ml.train_cnn import TFLITE, Int8Model  # noqa: E402

FW = ROOT / "firmware"
PER_CLASS = 40
# Largest allowed int8 softmax difference between host reference kernels and TFLite Micro on
# Xtensa (1 unit = 1/256). Set from observed runs, not derived: 6 for the 2026-11-05 model,
# 7 for the 2026-11-11 retrain. Class agreement on all vectors is the strict check.
MAX_SCORE_DIFF = 7
PIO_DIR = ROOT / ".tools" / "pio"
QEMU = ROOT / ".tools" / "qemu" / "bin" / "qemu-system-xtensa.exe"
SCALE_RE = re.compile(r'\{"(Demo \w+)", DEMO_DATA_(\d+), (\d+), ([\d.]+)f\}')


def floats(row):
    return ",".join(f"{float(v):.9g}f" if float(v) != int(v) else f"{int(v)}.0f" for v in row)


def write_vectors(cnn):
    d = load_split("test_mit", "test_ptb")
    rng = np.random.default_rng(3)
    pick = np.concatenate([rng.choice(np.flatnonzero(d["y"] == c), PER_CLASS, replace=False) for c in range(len(CLASSES))])
    wave, ctx, morph = d["wave"][pick], d["ctx"][pick], d["morph"][pick]
    pred, scores = cnn.predict(wave, ctx)
    rf = rf_predict(rf_features({"ctx": ctx, "morph": morph}))
    L = ["// Generated by tools/run_qemu_selftest.py. Do not edit.", "#pragma once", "#include <stdint.h>", "",
         f"constexpr int ST_COUNT = {len(pick)};"]
    for name, arr, n in (("ST_WAVE", wave, 160), ("ST_CTX", ctx, 13), ("ST_MORPH", morph, 32)):
        L.append(f"static const float {name}[ST_COUNT][{n}] = {{")
        L += ["{" + floats(r) + "}," for r in arr]
        L.append("};")
    L.append("static const int8_t ST_SCORES[ST_COUNT][6] = {" + ",".join("{" + ",".join(map(str, r)) + "}" for r in scores) + "};")
    L.append("static const int8_t ST_CNN[ST_COUNT] = {" + ",".join(map(str, pred)) + "};")
    L.append("static const int8_t ST_RF[ST_COUNT] = {" + ",".join(map(str, rf)) + "};")
    (FW / "src" / "selftest_vectors.h").write_text("\n".join(L) + "\n")


def build():
    env = dict(os.environ, PLATFORMIO_CORE_DIR=str(PIO_DIR))
    pio = ROOT / ".venv" / "Scripts" / "pio.exe"
    subprocess.run([str(pio), "run", "-e", "qemu_selftest"], cwd=FW, env=env, check=True, stdout=subprocess.DEVNULL)
    b = FW / ".pio" / "build" / "qemu_selftest"
    boot = next(PIO_DIR.glob("packages/framework-arduinoespressif32/tools/partitions/boot_app0.bin"))
    esptool = next(PIO_DIR.glob("packages/tool-esptoolpy/esptool.py"))
    image = b / "flash.bin"
    subprocess.run([sys.executable, str(esptool), "--chip", "esp32", "merge_bin", "--fill-flash-size", "4MB", "-o", str(image),
                    "0x1000", str(b / "bootloader.bin"), "0x8000", str(b / "partitions.bin"), "0xe000", str(boot),
                    "0x10000", str(b / "firmware.bin")], check=True, stdout=subprocess.DEVNULL)
    return image


def run_qemu(image, timeout=900):
    p = subprocess.Popen([str(QEMU), "-nographic", "-machine", "esp32", "-m", "4M", "-drive", f"file={image},if=mtd,format=raw",
                          "-serial", "stdio", "-monitor", "none", "-display", "none"],
                         stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, errors="ignore")
    return collect_output(p, timeout)


def collect_output(process, timeout):
    """Bound execution even when the emulator produces no output."""
    output = queue.Queue()

    def read():
        try:
            for line in process.stdout:
                output.put(line)
        finally:
            output.put(None)

    reader = threading.Thread(target=read, daemon=True)
    reader.start()
    lines, deadline = [], time.monotonic() + timeout
    try:
        while time.monotonic() < deadline:
            try:
                line = output.get(timeout=max(0.001, deadline - time.monotonic()))
            except queue.Empty:
                break
            if line is None:
                break
            lines.append(line.strip())
            print(line.rstrip(), flush=True)
            if any(marker in line for marker in ("SELFTEST,done", "model_load_failed", "Backtrace")):
                break
    finally:
        if process.poll() is None:
            process.kill()
        process.wait()
        reader.join(timeout=2)
        process.stdout.close()
    return lines


def validate_result(result):
    """Return failures; small CNN score/count differences are explicit tolerances."""
    errors = []
    if not result.get("booted") or not result.get("done"):
        errors.append("Emulator did not complete the self-test")
    try:
        v = result["vectors"]
        count = int(v["count"])
        if count != PER_CLASS * len(CLASSES) or any(int(v[k]) != count for k in ("cnn_match", "rf_match")):
            errors.append("Vector class predictions differ")
        if int(v["max_score_diff"]) not in range(MAX_SCORE_DIFF + 1):
            errors.append(f"CNN score difference exceeds {MAX_SCORE_DIFF} quantized units")
        if int(result["model"]["arena_bytes"]) <= 0:
            errors.append("Invalid tensor arena size")
    except (KeyError, ValueError, TypeError):
        errors.append("Missing or malformed model/vector results")
    clips = result.get("clips", [])
    if len(clips) != 6 or len({c.get("clip") for c in clips}) != 6:
        errors.append("Expected six distinct demo clips")
    for clip in clips:
        try:
            host, device = clip["host"], clip["esp32"]
            if any(int(device[k]) != host[k] for k in ("detected", "analysed")):
                errors.append(clip["clip"] + ": beat counts differ")
            if device["rhythm"] != host["rhythm"]:
                errors.append(clip["clip"] + ": CNN verdict differs")
            for key, tolerance in (("cnn", 1), ("rf", 0)):
                counts = [int(v) for v in device[key].split()]
                if len(counts) != 6 or sum(counts) != host["analysed"] or any(abs(a-b) > tolerance for a, b in zip(counts, host[key])):
                    errors.append(clip["clip"] + ": " + key + " class counts differ")
        except (KeyError, ValueError, TypeError):
            errors.append(clip.get("clip", "Unknown clip") + ": missing or malformed result")
    return errors



def clip_signals():
    text = (FW / "src" / "demo_clips.h").read_text()
    out = []
    for name, i, length, scale in SCALE_RE.findall(text):
        body = text[text.index(f"DEMO_DATA_{i}["):]
        body = body[body.index("{") + 1: body.index("}")]
        out.append((name, np.array(body.replace("\n", "").strip(",").split(","), dtype=np.float32) * float(scale)))
    return out


def expected_clip(cnn, name, mv):
    b = run_core(mv)[0]
    ok = b[(b["flags"] & (READY | GOOD_SQ)) == (READY | GOOD_SQ)]
    c = rhythm_rule(cnn.predict(ok["wave"], ok["ctx"])[0], ok["ctx"])
    r = rhythm_rule(rf_predict(rf_features({"ctx": ok["ctx"], "morph": ok["morph"]})), ok["ctx"])
    lab = rhythm(c)[0]
    return {"detected": len(b), "analysed": len(ok), "rhythm": CLASSES[lab[-1]] if len(lab) and lab[-1] >= 0 else "-",
            "cnn": np.bincount(c, minlength=6).tolist(), "rf": np.bincount(r, minlength=6).tolist()}


def main():
    cnn = Int8Model(TFLITE)
    write_vectors(cnn)
    lines = run_qemu(build())
    res = {"booted": any("SELFTEST,boot" in l for l in lines), "done": any("SELFTEST,done" in l for l in lines), "clips": []}
    for l in lines:
        if l.startswith("VECTORS,"):
            res["vectors"] = dict(kv.split("=") for kv in l.split(",")[1:])
        if l.startswith("MODEL,"):
            res["model"] = dict(kv.split("=") for kv in l.split(",")[1:])
    clips = {l.split(",")[1]: l for l in lines if l.startswith("CLIP,")}
    for name, mv in clip_signals():
        exp = expected_clip(cnn, name, mv)
        line = clips.get(name, "")
        got = dict(kv.split("=") for kv in line.split(",")[2:]) if line else {}
        res["clips"].append({"clip": name, "host": exp, "esp32": got})
        print(name, "host", exp, "\n   esp32", got)
    res["failures"] = validate_result(res)
    res["passed"] = not res["failures"]
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "qemu_selftest.json").write_text(json.dumps(res, indent=1))
    print(json.dumps({k: res.get(k) for k in ("booted", "done", "model", "vectors")}, indent=1))

    if res["failures"]:
        raise SystemExit("Self-test failed: " + "; ".join(res["failures"]))


if __name__ == "__main__":
    main()
