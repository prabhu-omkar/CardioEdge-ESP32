"""Trains classifier 2: the Random Forest, and exports it as a C header.

The ESP32 uses a majority vote of tree leaves, so that is also what is scored here.

    python -m ml.train_rf
"""
import json
import pickle

import numpy as np
from sklearn.ensemble import RandomForestClassifier

from .common import MODELS, RESULTS, load_split, metrics, rf_features, sample_weights
from .core import ROOT

GRID = [
    {"n_estimators": 30, "max_depth": 10, "max_leaf_nodes": 200},
    {"n_estimators": 30, "max_depth": 14, "max_leaf_nodes": 400},
    {"n_estimators": 50, "max_depth": 12, "max_leaf_nodes": 300},
    {"n_estimators": 50, "max_depth": 16, "max_leaf_nodes": 600},
]
HEADER = ROOT / "firmware" / "src" / "model_rf.h"


def fit(params, X, y, rec):
    rf = RandomForestClassifier(min_samples_leaf=3, max_features="sqrt", n_jobs=-1, random_state=7, **params)
    return rf.fit(X, y, sample_weight=sample_weights(y, rec))


def hard_vote(rf, X):
    """Majority vote of the leaf classes, exactly as the device computes it."""
    votes = np.zeros((len(X), rf.n_classes_), dtype=np.int32)
    for est in rf.estimators_:
        t = est.tree_
        leaf_class = np.argmax(t.value[:, 0, :], axis=1)
        votes[np.arange(len(X)), leaf_class[est.apply(X)]] += 1
    return rf.classes_[np.argmax(votes, axis=1)]


def export_header(rf, path):
    """Flat node table. feature < 0 marks a leaf and its value is in `left`."""
    feats, thr, left, right, roots = [], [], [], [], []
    for est in rf.estimators_:
        t = est.tree_
        base = len(feats)
        roots.append(base)
        leaf_class = rf.classes_[np.argmax(t.value[:, 0, :], axis=1)]
        for i in range(t.node_count):
            if t.children_left[i] < 0:
                feats.append(-1); thr.append(0.0); left.append(int(leaf_class[i])); right.append(0)
            else:
                feats.append(int(t.feature[i])); thr.append(float(t.threshold[i]))
                left.append(base + int(t.children_left[i])); right.append(base + int(t.children_right[i]))
    assert len(feats) < 65536
    fmt = lambda vals, f: ",".join(f.format(v) for v in vals)
    path.write_text(
        "// Generated by ml/train_rf.py. Do not edit.\n#pragma once\n#include <stdint.h>\n\n"
        f"constexpr int RF_N_TREES = {len(roots)};\nconstexpr int RF_N_NODES = {len(feats)};\n"
        f"static const uint16_t rf_roots[RF_N_TREES] = {{{fmt(roots, '{}')}}};\n"
        f"static const int8_t rf_feature[RF_N_NODES] = {{{fmt(feats, '{}')}}};\n"
        f"static const float rf_threshold[RF_N_NODES] = {{{fmt(thr, '{:.7g}f')}}};\n"
        f"static const uint16_t rf_left[RF_N_NODES] = {{{fmt(left, '{}')}}};\n"
        f"static const uint16_t rf_right[RF_N_NODES] = {{{fmt(right, '{}')}}};\n".replace(",0f", ",0.0f").replace("{0f", "{0.0f")
    )
    return len(feats)


def main():
    MODELS.mkdir(exist_ok=True); RESULTS.mkdir(exist_ok=True)
    tr, va = load_split("train"), load_split("val")
    Xt, Xv = rf_features(tr), rf_features(va)
    best = None
    for p in GRID:
        rf = fit(p, Xt, tr["y"], tr["rec"])
        m = metrics(va["y"], hard_vote(rf, Xv))
        print(p, f"val macro-F1 {m['macro_f1']:.4f} acc {m['accuracy']:.4f}", flush=True)
        if best is None or m["macro_f1"] > best[1]:
            best = (p, m["macro_f1"])
    rf = fit(best[0], np.vstack([Xt, Xv]), np.concatenate([tr["y"], va["y"]]), np.concatenate([tr["rec"], va["rec"]]))
    with open(MODELS / "rf.pkl", "wb") as f:
        pickle.dump(rf, f)
    nodes = export_header(rf, HEADER)
    info = {"params": best[0], "val_macro_f1": best[1], "nodes": nodes, "flash_kb": nodes * 9 / 1024}
    (RESULTS / "rf_training.json").write_text(json.dumps(info, indent=1))
    print(info)


if __name__ == "__main__":
    main()
