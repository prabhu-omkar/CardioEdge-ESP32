"""Cuts demo clips into firmware flash so abnormal rhythms can be shown without a patient.

Clips come only from test-set (DS2) patients, so the demo is not played from data the
models were trained on. Each clip is the 60 s stretch where its class is most dominant.
A noise clip uses the electrode-motion recording from the noise stress test database.

    python -m ml.export_demo
"""
import json

import numpy as np
import wfdb

from .core import CLASSES, FS, ROOT
from .dataset import DS2, RAW, ensure_mitdb, load_mit, to_fs

CLIP_SECONDS = 60
SCALE_MV = 0.005  # mV per stored count
HEADER = ROOT / "firmware" / "src" / "demo_clips.h"
SOURCES = [("Normal", 0, 100), ("PVC", 1, 233), ("AFib", 2, 202), ("LBBB", 3, 214), ("RBBB", 4, 212)]


def best_segment(idx, lab, cls, length):
    """Start sample of the window holding the largest share of `cls` beats."""
    n = length
    centres = np.arange(0, max(idx[-1] - n, 1), FS * 5)
    scores = [np.mean(lab[(idx >= s) & (idx < s + n)] == cls) if np.any((idx >= s) & (idx < s + n)) else 0 for s in centres]
    return int(centres[int(np.argmax(scores))]), float(np.max(scores))


def noisy_clip(base):
    sig, _, _ = load_mit(100, base)
    em = wfdb.rdrecord(str(RAW / "nst" / "em")).p_signal[:, 0]
    em = to_fs(em, 360)
    n = CLIP_SECONDS * FS
    # Clean for 25 s, then 20 s of heavy motion artefact, then clean again
    clip = sig[:n].copy()
    a, b = 25 * FS, 45 * FS
    clip[a:b] += 2.0 * em[FS * 60: FS * 60 + b - a]
    return clip


def main():
    base = ensure_mitdb()
    clips, info = [], []
    n = CLIP_SECONDS * FS
    for name, cls, rec in SOURCES:
        assert rec in DS2
        sig, idx, lab = load_mit(rec, base)
        s, purity = best_segment(idx, lab, cls, n)
        clips.append((f"Demo {name}", sig[s:s + n]))
        info.append({"clip": name, "record": rec, "start_s": s / FS, "class_share": round(purity, 3)})
        print(info[-1])
    clips.append(("Demo Noise", noisy_clip(base)))
    info.append({"clip": "Noise", "record": 100, "note": "electrode motion added from 25 s to 45 s"})

    lines = ["// Generated by ml/export_demo.py. Do not edit.", "#pragma once", "#include <pgmspace.h>", "#include <stdint.h>", "",
             "struct DemoClip { const char* name; const int16_t* data; uint32_t length; float scale_mv; };", ""]
    for i, (name, sig) in enumerate(clips):
        vals = np.clip(np.round(sig / SCALE_MV), -32768, 32767).astype(int)
        lines.append(f"static const int16_t DEMO_DATA_{i}[{len(vals)}] PROGMEM = {{")
        lines += [",".join(map(str, vals[k:k + 24])) + "," for k in range(0, len(vals), 24)]
        lines.append("};")
    lines.append(f"constexpr int DEMO_CLIP_COUNT = {len(clips)};")
    lines.append("static const DemoClip DEMO_CLIPS[DEMO_CLIP_COUNT] = {")
    for i, (name, sig) in enumerate(clips):
        lines.append(f'  {{"{name}", DEMO_DATA_{i}, {len(sig)}, {SCALE_MV}f}},')
    lines.append("};")
    HEADER.write_text("\n".join(lines) + "\n")
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results" / "demo_clips.json").write_text(json.dumps(info, indent=1))


if __name__ == "__main__":
    main()
